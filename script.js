/* 5. Stats Counter Animation */
function initStatsCounter() {
    const statNumbers = document.querySelectorAll(".em-stat-number");
    let animated = false;

    function startCounting() {
        const statsSection = document.querySelector(".em-stats-bar");
        if (!statsSection || animated) return;

        const rect = statsSection.getBoundingClientRect();
        if (rect.top <= window.innerHeight && rect.bottom >= 0) {
            animated = true;
            statNumbers.forEach(stat => {
                const target = parseInt(stat.getAttribute("data-target"), 10);
                const suffix = stat.getAttribute("data-suffix") || "";
                let current = 0;
                const duration = 1000;
                const stepTime = 30;
                const increment = Math.max(1, Math.ceil(target / (duration / stepTime)));

                const timer = setInterval(() => {
                    current += increment;
                    if (current >= target) {
                        current = target;
                        stat.dataset.animatedDone = "1";
                        clearInterval(timer);
                    }
                    const currentSuffix = stat.getAttribute("data-suffix") || "";
                    stat.textContent = current + currentSuffix;
                }, stepTime);
            });
        }
    }

    window.addEventListener("scroll", startCounting, { passive: true });
    startCounting();
}

